EXTRA_HOURS = 3.0

def osrm(a, b):
    """Часі + км дорогою між координатами (лат, lon)."""
    (alat, alon), (blat, blon) = a, b
    url = f"https://router.project-osrm.org/route/v1/driving/{alon},{alat};{blon},{blat}?overview=false"
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "bez-mezh-site/1.0"})
            with urllib.request.urlopen(req, timeout=30) as r:
                j = json.load(r)
            route = j["routes"][0]
            return round(route["duration"] / 3600 + EXTRA_HOURS, 1), round(route["distance"] / 1000)
        except Exception as e:
            print(f"  OSRM retry {attempt+1} {a}->{b}: {e}")
            time.sleep(2)
    return None, None

_TR_SRC = "абвгґдеєжзиіїйклмнопрстуфхцчшщьюя'’ "
_TR_DST = ["a","b","v","h","g","d","e","ye","zh","z","y","i","yi","y",
           "k","l","m","n","o","p","r","s","t","u","f","kh","ts","ch",
           "sh","shch","yu","ya","-","-","-"]
TR = {ord(s): t for s, t in zip(_TR_SRC, _TR_DST)}

def slug(city):
    return city.lower().translate(TR).replace("--", "-").strip("-")

